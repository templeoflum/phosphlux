#!/usr/bin/env python3
"""Tabulate U2/D5/D6 crossover correction against CIRCUIT.md stage 9's ideal V.
Only the rectifier correction is retained; ramp, reference and reset stay in the app.
Run from any directory with python3; requires ngspice. Scratch stays in the repo.
"""
import bisect
import importlib.util
from pathlib import Path
import subprocess
import sys

sys.dont_write_bytecode = True

ROOT = Path(__file__).resolve().parents[1]
WORK = ROOT.parents[2] / '.scratch' / 'cadet_iv_triangle'
WORK.mkdir(parents=True, exist_ok=True)
spec = importlib.util.spec_from_file_location('cadet_sim', ROOT / 'sim/run_sims.py')
sim = importlib.util.module_from_spec(spec)
spec.loader.exec_module(sim)
N = 121
values = []
for j in range(9):
    pos = j / 8
    dat = WORK / f'trim{pos:.3f}.dat'
    lib = ROOT / 'sim/cadet_iv.lib'
    text = lib.read_text()
    rectifier = text[text.index('R13 ramp na'):text.index('.ends RAMPCH')]
    slope = (4.99 + 10 * pos) / 14.99 * (0.99753e-3 / 56e-9)
    deck = f"""* Isolated Cadet IV U2/D5/D6 at H trim {pos}
.include {lib}
XPWR vcc vee POWER
XREF vcc vee m2 MINUS2REF
VINPUT ramp 0 PWL(0 0 5u 0 150u {slope * 145e-6})
{rectifier}
.options method=gear reltol=1e-4
.tran 20n 150u 0 50n
.control
set wr_singlescale
set wr_vecnames
run
linearize
wrdata {dat} v(ramp) v(jtri) v(m2)
.endc
.end
"""
    # Keep the settled rise, including the bottom even when it is outside the picture.
    cir = dat.with_suffix('.cir')
    cir.write_text(deck)
    p = subprocess.run(['ngspice', '-b', str(cir)], capture_output=True, text=True)
    dat.with_suffix('.log').write_text(p.stdout + p.stderr)
    if p.returncode:
        raise RuntimeError(f'ngspice {cir}: exit {p.returncode}')
    rows = [[float(x) for x in l.split()] for l in dat.read_text().splitlines()[1:]]
    xs = [r[1] - abs(r[3]) * 499 / 2000 for r in rows]
    ys = [r[2] - 1000 / 499 * abs(x) for r, x in zip(rows, xs)]
    for i in range(N):
        x = -0.03 + i * 0.0005
        k = max(1, min(bisect.bisect_left(xs, x), len(xs)-1))
        y = ys[k-1] + (ys[k]-ys[k-1]) * (x-xs[k-1]) / (xs[k]-xs[k-1])
        values.append(y)
    print(f'trim {pos:.3f}: ngspice exit {p.returncode}')
lines = ['// Generated by triangle/build_table.py; evidence and limits: TRIANGLE_BOTTOM.md.',
         '// Correction in volts: trim rows 0..1 by 0.125, delta ramp -0.03..0.03 by 0.0005.',
         f'pub const H_TRI_CORRECTION: [f64; {len(values)}] = [']
for j in range(9):
    lines.append(f'    // H trim {j/8:.3f}')
    for i in range(0,N,8):
        lines.append('    '+', '.join(f'{v:.8f}' for v in values[j*N+i:j*N+min(i+8,N)])+',')
lines.append('];')
(ROOT / 'triangle/correction.rs').write_text('\n'.join(lines)+'\n')
